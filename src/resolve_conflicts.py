"""
Step 4: Resolve Conflicts.

Uses textual similarity to evaluate candidates generated by Step 3.

Final similarity:
    60% Content Similarity
    40% Context Similarity
"""

from __future__ import annotations
import math
import re
from .preprocessing import preprocess
from .generate_candidates import CandidateListResult


CONTENT_WEIGHT = 0.6
CONTEXT_WEIGHT = 0.4
THRESHOLD = 0.45


def calculate_text_similarity(old_line: str, new_line: str) -> float:
    """Calculate similarity using manual Levenshtein distance."""
    max_length = max(len(old_line), len(new_line))

    if max_length == 0:
        return 1.0

    previous_row = list(range(len(new_line) + 1))

    for i, old_char in enumerate(old_line, start=1):
        current_row = [i]

        for j, new_char in enumerate(new_line, start=1):
            insertion = current_row[j - 1] + 1
            deletion = previous_row[j] + 1
            substitution = previous_row[j - 1] + (
                0 if old_char == new_char else 1
            )

            current_row.append(min(insertion, deletion, substitution))

        previous_row = current_row

    distance = previous_row[-1]
    return 1.0 - distance / max_length

def extract_context(
    lines: list[str],
    target_index: int,
    window: int = 4,
) -> dict:
    """Collect up to four lines before and after the target line."""
    above = []
    below = []

    for offset in range(1, window + 1):
        index = target_index - offset
        if index >= 0:
            above.append(lines[index])

        index = target_index + offset
        if index < len(lines):
            below.append(lines[index])

    above.reverse()

    return {"above": above, "below": below}

def calculate_context_similarity(old_context: dict, new_context: dict) -> float:
    """Compare surrounding text using cosine similarity of word counts."""
    old_text = " ".join(
        old_context.get("above", []) + old_context.get("below", [])
    )
    new_text = " ".join(
        new_context.get("above", []) + new_context.get("below", [])
    )

    old_counts = {}
    new_counts = {}

    for word in re.findall(r"\w+", old_text.lower()):
        old_counts[word] = old_counts.get(word, 0) + 1

    for word in re.findall(r"\w+", new_text.lower()):
        new_counts[word] = new_counts.get(word, 0) + 1

    dot_product = sum(
        count * new_counts.get(word, 0)
        for word, count in old_counts.items()
    )

    old_length = math.sqrt(sum(count ** 2 for count in old_counts.values()))
    new_length = math.sqrt(sum(count ** 2 for count in new_counts.values()))

    if old_length == 0 or new_length == 0:
        return 0.0

    return dot_product / (old_length * new_length)

def combined_similarity(
    old_line: str,
    new_line: str,
    old_context: dict,
    new_context: dict,
) -> float:
    """Calculate final textual similarity.
    60% content similarity (Levenshtein)
    40% context similarity (word-count cosine)"""

    content_score = calculate_text_similarity(old_line, new_line)

    context_score = calculate_context_similarity(
        old_context,
        new_context
    )

    final_score = (
        CONTENT_WEIGHT * content_score
        + CONTEXT_WEIGHT * context_score
    )

    return final_score

def resolve_conflicts(
    old_raw: list[str],
    new_raw: list[str],
    candidates: CandidateListResult,
    threshold: float = THRESHOLD,
) -> dict[int, int]:
    """
    Step 4: Resolve candidate matches.

    Receives Step 3 candidates and returns
    a mapping of old line numbers to new line numbers.
    """

    old_norm = preprocess(old_raw)
    new_norm = preprocess(new_raw)

    proposals = []

    for candidate in candidates.all_candidates():
        old_no = candidate.old_line
        new_no = candidate.new_line

        old_index = old_no - 1
        new_index = new_no - 1

        old_line = old_norm[old_index]
        new_line = new_norm[new_index]

        old_context = extract_context(old_norm, old_index)
        new_context = extract_context(new_norm, new_index)

        score = combined_similarity(
            old_line,
            new_line,
            old_context,
            new_context,
        )

        if score > threshold:
            proposals.append((score, old_no, new_no))

        # Sort candidates by highest similarity first.
    # If scores are equal, prefer the smaller line movement.
    proposals.sort(
        key=lambda item: (
            -item[0],
            abs(item[1] - item[2]),
            item[1],
            item[2],
        )
    )

    used_old = set()
    used_new = set()
    matches = {}

    for score, old_no, new_no in proposals:

        # Skip if either line is already matched.
        if old_no in used_old or new_no in used_new:
            continue

        # Accept the match.
        matches[old_no] = new_no

        # Mark both lines as used.
        used_old.add(old_no)
        used_new.add(new_no)

    return dict(sorted(matches.items()))